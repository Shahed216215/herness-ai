'use strict';

const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const XLSX = require('xlsx');

const {
  buildRealFormat,
  verifyRealFormat
} = require('../services/deliverable-real-format-builder');

(async () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'mira-real-format-'));

  try {
    for (const format of ['XLSX', 'DOCX', 'PDF', 'CODE_PACKAGE']) {
      const ext = {
        XLSX: '.xlsx',
        DOCX: '.docx',
        PDF: '.pdf',
        CODE_PACKAGE: '.zip'
      }[format];

      const outputPath = path.join(root, `${format.toLowerCase()}${ext}`);

      await buildRealFormat({
        outputPath,
        format,
        title: `Mira ${format} Test`,
        content: {
          message: 'Real format verification',
          format
        }
      });

      assert(fs.existsSync(outputPath));
      assert(fs.statSync(outputPath).size > 0);
      assert.strictEqual(
        verifyRealFormat(outputPath, format),
        true,
        `${format} signature invalid`
      );

      if (format === 'XLSX') {
        const workbook = XLSX.readFile(outputPath, {
          cellFormula: false,
          cellHTML: false
        });
        assert.deepStrictEqual(workbook.SheetNames, ['Deliverable']);
        const rows = XLSX.utils.sheet_to_json(
          workbook.Sheets.Deliverable,
          { header: 1, defval: '' }
        );
        assert.strictEqual(rows[0][0], 'Deliverable');
        assert.strictEqual(rows[0][1], 'Mira XLSX Test');
        assert.strictEqual(rows[1][0], 'Generated By');
        assert.strictEqual(rows[1][1], 'Mira AI Agent');
        assert.strictEqual(rows[2][0], 'Content');
        assert.ok(String(rows[2][1]).includes('Real format verification'));
      }
    }

    console.log('STAGE10_1_REAL_FORMATS: PASS');
    console.log('XLSX: REAL OOXML WRITE/READ ROUNDTRIP: PASS');
    console.log('DOCX: REAL ZIP/OOXML: PASS');
    console.log('PDF: REAL PDF SIGNATURE: PASS');
    console.log('CODE_PACKAGE: REAL ZIP: PASS');
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
})();
