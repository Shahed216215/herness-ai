const path = require('path');
const XLSX = require('xlsx');
const { Document, Packer, Paragraph, TextRun, HeadingLevel } = require('docx');
const PDFDocument = require('pdfkit');

'use strict';

const fs = require('fs');
function ensureDir(filePath) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
}

function textFromContent(content) {
  if (content === undefined || content === null) return '';
  if (typeof content === 'string') return content;
  return JSON.stringify(content, null, 2);
}

async function buildXLSX({ outputPath, title, content }) {
  ensureDir(outputPath);

  const text = textFromContent(content);
  const rows = [
    ['Deliverable', title || 'Mira Deliverable'],
    ['Generated By', 'Mira AI Agent'],
    ['Content', text]
  ];

  const ws = XLSX.utils.aoa_to_sheet(rows);
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, 'Deliverable');

  XLSX.writeFile(wb, outputPath);

  return outputPath;
}

async function buildDOCX({ outputPath, title, content }) {
  ensureDir(outputPath);

  const text = textFromContent(content);

  const doc = new Document({
    sections: [{
      children: [
        new Paragraph({
          text: title || 'Mira Deliverable',
          heading: HeadingLevel.TITLE
        }),
        new Paragraph({
          text: 'Generated by Mira AI Agent'
        }),
        new Paragraph({
          text
        })
      ]
    }]
  });

  const buffer = await Packer.toBuffer(doc);
  fs.writeFileSync(outputPath, buffer);

  return outputPath;
}

async function buildPDF({ outputPath, title, content }) {
  ensureDir(outputPath);

  return await new Promise((resolve, reject) => {
    const doc = new PDFDocument();
    const stream = fs.createWriteStream(outputPath);

    stream.on('finish', () => resolve(outputPath));
    stream.on('error', reject);

    doc.pipe(stream);
    doc.fontSize(20).text(title || 'Mira Deliverable');
    doc.moveDown();
    doc.fontSize(10).text('Generated by Mira AI Agent');
    doc.moveDown();
    doc.fontSize(12).text(textFromContent(content));
    doc.end();
  });
}

async function buildCodePackage(outputPath, content) {
  ensureDir(outputPath);

  const zlib = require('zlib');

  /*
   * Native ZIP writer.
   *
   * We intentionally avoid the archiver package because the installed
   * Termux/CJS environment exposes a non-callable archiver export.
   *
   * This creates a standards-compliant ZIP containing:
   *   - README.txt
   *   - package-manifest.json
   */

  const sourceText = textFromContent(content);

  const entries = [
    {
      name: 'README.txt',
      data: Buffer.from(sourceText, 'utf8')
    },
    {
      name: 'package-manifest.json',
      data: Buffer.from(
        JSON.stringify(
          {
            type: 'MIRA_CODE_PACKAGE',
            generatedAt: new Date().toISOString(),
            description: 'Mira AI Agent code package'
          },
          null,
          2
        ),
        'utf8'
      )
    }
  ];

  const crc32 = buffer => {
    let crc = 0xffffffff;

    for (const byte of buffer) {
      crc ^= byte;

      for (let i = 0; i < 8; i++) {
        crc =
          (crc >>> 1) ^
          (
            (crc & 1)
              ? 0xedb88320
              : 0
          );
      }
    }

    return (crc ^ 0xffffffff) >>> 0;
  };

  const u16 = n => {
    const b = Buffer.alloc(2);
    b.writeUInt16LE(n & 0xffff, 0);
    return b;
  };

  const u32 = n => {
    const b = Buffer.alloc(4);
    b.writeUInt32LE(n >>> 0, 0);
    return b;
  };

  const localParts = [];
  const centralParts = [];

  let offset = 0;

  for (const entry of entries) {
    const name = Buffer.from(entry.name, 'utf8');
    const data = entry.data;
    const compressed = zlib.deflateRawSync(data, { level: 9 });
    const crc = crc32(data);

    const localHeader = Buffer.concat([
      Buffer.from([0x50, 0x4b, 0x03, 0x04]),
      u16(20),
      u16(0),
      u16(8),
      u16(0),
      u16(0),
      u32(crc),
      u32(compressed.length),
      u32(data.length),
      u16(name.length),
      u16(0),
      name
    ]);

    localParts.push(localHeader, compressed);

    const centralHeader = Buffer.concat([
      Buffer.from([0x50, 0x4b, 0x01, 0x02]),
      u16(20),
      u16(20),
      u16(0),
      u16(8),
      u16(0),
      u16(0),
      u32(crc),
      u32(compressed.length),
      u32(data.length),
      u16(name.length),
      u16(0),
      u16(0),
      u16(0),
      u16(0),
      u32(0),
      u32(offset),
      name
    ]);

    centralParts.push(centralHeader);

    offset += localHeader.length + compressed.length;
  }

  const centralDirectory = Buffer.concat(centralParts);
  const localData = Buffer.concat(localParts);

  const endRecord = Buffer.concat([
    Buffer.from([0x50, 0x4b, 0x05, 0x06]),
    u16(0),
    u16(0),
    u16(entries.length),
    u16(entries.length),
    u32(centralDirectory.length),
    u32(localData.length),
    u16(0)
  ]);

  const zip = Buffer.concat([
    localData,
    centralDirectory,
    endRecord
  ]);

  fs.writeFileSync(outputPath, zip);

  return {
    outputPath,
    size: zip.length
  };
}

function verifyRealFormat(filePath, format) {
  const data = fs.readFileSync(filePath);
  const f = String(format || '').toUpperCase();

  if (f === 'PDF') {
    return data.subarray(0, 5).toString() === '%PDF-';
  }

  if (f === 'XLSX' || f === 'DOCX' || f === 'CODE_PACKAGE') {
    return data.length >= 4 &&
      data[0] === 0x50 &&
      data[1] === 0x4b &&
      data[2] === 0x03 &&
      data[3] === 0x04;
  }

  return false;
}





async function buildRealFormat(input, outputPath, content) {
  let format;
  let actualOutputPath;
  let actualContent;
  let title;

  if (
    input &&
    typeof input === 'object' &&
    !Buffer.isBuffer(input) &&
    !Array.isArray(input)
  ) {
    format = input.format || input.type || input.requiredFormat;
    actualOutputPath =
      input.outputPath ||
      input.filePath ||
      input.path ||
      outputPath;

    actualContent =
      input.content !== undefined
        ? input.content
        : input.data;

    title = input.title || 'Mira Deliverable';
  } else {
    format = input;
    actualOutputPath = outputPath;
    actualContent = content;
    title = 'Mira Deliverable';
  }

  const normalized = String(format || '')
    .trim()
    .toUpperCase()
    .replace(/[\s-]+/g, '_');

  switch (normalized) {
    case 'XLSX':
      return buildXLSX({
        outputPath: actualOutputPath,
        title,
        content: actualContent
      });

    case 'DOCX':
      return buildDOCX({
        outputPath: actualOutputPath,
        title,
        content: actualContent
      });

    case 'PDF':
      return buildPDF({
        outputPath: actualOutputPath,
        title,
        content: actualContent
      });

    case 'CODE_PACKAGE':
    case 'CODE':
    case 'ZIP':
      return buildCodePackage(
        actualOutputPath,
        actualContent
      );

    default:
      throw new Error(
        `UNSUPPORTED_REAL_FORMAT:${format}`
      );
  }
}

module.exports = {
  buildXLSX,
  buildDOCX,
  buildPDF,
  buildCodePackage,
  verifyRealFormat,
  buildRealFormat
};
